export const DEFAULT_LANGUAGE = "vi";

export const LANGUAGES = {
  vi: { code: "vi", locale: "vi-VN", name: "Tiếng Việt" },
  en: { code: "en", locale: "en-US", name: "English" },
  zh: { code: "zh", locale: "zh-CN", name: "中文" },
  th: { code: "th", locale: "th-TH", name: "ภาษาไทย" },
};

export const LANGUAGE_CODES = Object.keys(LANGUAGES);

function normalizeLanguage(value) {
  const normalized = String(value || "").trim().toLowerCase();
  if (normalized === "zh" || normalized === "zh-cn" || normalized.startsWith("zh-")) return "zh";
  if (normalized === "th" || normalized === "th-th" || normalized.startsWith("th-")) return "th";
  if (normalized === "vi" || normalized.startsWith("vi-")) return "vi";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  return null;
}

export function resolveLanguage(storedLanguage, browserLanguage) {
  return (
    normalizeLanguage(storedLanguage) ||
    normalizeLanguage(browserLanguage) ||
    DEFAULT_LANGUAGE
  );
}

export function getInitialLanguage() {
  let storedLanguage = null;
  try {
    storedLanguage = window.localStorage.getItem("dinh_lang");
  } catch {
    // Continue with the browser locale when storage is unavailable.
  }
  return resolveLanguage(storedLanguage, navigator.language);
}

export function localizedField(item, field, language) {
  if (!item) return "";
  const value =
    item.translations?.[language]?.[field] ?? item[`${field}_${language}`];
  return typeof value === "string" ? value : "";
}

